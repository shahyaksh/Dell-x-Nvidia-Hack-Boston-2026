// FlowDesk agent console: chat with local-LLM agents, live traces, charts, escalations.
(function () {
  const $ = (s, el = document) => el.querySelector(s);
  const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  const store = { get: (k) => { try { return localStorage.getItem(k); } catch (e) { return null; } },
                  set: (k, v) => { try { localStorage.setItem(k, v); } catch (e) {} } };
  let session = new URLSearchParams(location.search).get("s") || store.get("fd-session") || newId();
  let mode = store.get("fd-mode") || "harness";
  let busy = false;
  const charts = [];

  function newId() { return "s" + Date.now().toString(36) + Math.random().toString(36).slice(2, 6); }

  // ---------- markdown-lite (headings, bold, code, bullets, tables)
  function md(text) {
    const lines = esc(text).split("\n");
    let html = "", inList = false, table = [];
    const inline = (s) => s.replace(/\*\*(.+?)\*\*/g, "<b>$1</b>").replace(/`([^`]+)`/g, "<code>$1</code>");
    const flushTable = () => {
      if (!table.length) return;
      const rows = table.filter((r) => !/^\s*\|?\s*[-:| ]+\|?\s*$/.test(r));
      html += "<div class='tbl'><table>" + rows.map((r, i) => {
        const cells = r.replace(/^\s*\|/, "").replace(/\|\s*$/, "").split("|");
        return "<tr>" + cells.map((c) => (i === 0 ? "<th>" : "<td>") + inline(c.trim()) + (i === 0 ? "</th>" : "</td>")).join("") + "</tr>";
      }).join("") + "</table></div>";
      table = [];
    };
    for (const l of lines) {
      if (/^\s*\|.*\|\s*$/.test(l)) { if (inList) { html += "</ul>"; inList = false; } table.push(l); continue; }
      flushTable();
      if (/^\s*[-*•]\s+/.test(l)) { if (!inList) { html += "<ul>"; inList = true; } html += "<li>" + inline(l.replace(/^\s*[-*•]\s+/, "")) + "</li>"; continue; }
      if (inList) { html += "</ul>"; inList = false; }
      if (/^#{1,4}\s/.test(l)) { html += "<h4>" + inline(l.replace(/^#+\s/, "")) + "</h4>"; continue; }
      html += l.trim() ? "<p>" + inline(l) + "</p>" : "";
    }
    flushTable();
    if (inList) html += "</ul>";
    return html;
  }

  // ---------- artifacts
  const PALETTE = ["#76b900", "#0b6bcb", "#e8710a", "#9334e6", "#d01884", "#12b5cb", "#c5221f", "#5f6368"];
  function renderChart(a, host) {
    const card = document.createElement("div");
    card.className = "artifact";
    card.innerHTML = `<div class="a-title">${esc(a.title)}</div>` +
      (a.data ? `<div class="chartbox"><canvas></canvas></div>` : "") +
      (a.explanation ? `<div class="explain">${md(a.explanation)}</div>` : "") +
      (a.sql ? `<details><summary>SQL generated by the analytics agent</summary><pre>${esc(a.sql)}</pre></details>` : "") +
      (a.rows && a.rows.length ? `<details><summary>Data (${a.rows.length} rows)</summary>${table(a.columns, a.rows)}</details>` : "") +
      (a.run_id ? `<a class="tracelink" href="#" data-run="${a.run_id}">view analytics-agent trace</a>` : "");
    host.appendChild(card);
    if (a.data && window.Chart) {
      const type = a.chart.type === "table" ? "bar" : a.chart.type;
      const pie = type === "pie";
      const ds = a.data.datasets.map((d, i) => ({ label: d.label, data: d.data,
        backgroundColor: pie ? a.data.labels.map((_, j) => PALETTE[j % PALETTE.length]) : PALETTE[i % PALETTE.length],
        borderColor: PALETTE[i % PALETTE.length], borderWidth: type === "line" ? 2 : 0, pointRadius: type === "line" ? 0 : 3, tension: 0.25 }));
      const fg = getComputedStyle(document.body).getPropertyValue("--mut").trim() || "#666";
      charts.push(new Chart($("canvas", card), { type, data: { labels: a.data.labels, datasets: ds },
        options: { responsive: true, maintainAspectRatio: false, animation: { duration: 300 },
          plugins: { legend: { display: pie || ds.length > 1, labels: { color: fg } } },
          scales: pie ? {} : { x: { ticks: { color: fg, maxRotation: 0, autoSkip: true } }, y: { ticks: { color: fg }, beginAtZero: true } } } }));
    }
  }
  function table(cols, rows) {
    return `<div class="tbl"><table><tr>${cols.map((c) => `<th>${esc(c)}</th>`).join("")}</tr>` +
      rows.map((r) => `<tr>${r.map((v) => `<td>${esc(typeof v === "number" && !Number.isInteger(v) ? v.toFixed(2) : v)}</td>`).join("")}</tr>`).join("") + "</table></div>";
  }
  function renderArtifacts(list, host) {
    for (const a of list || []) {
      if (a.type === "chart") renderChart(a, host);
      else if (a.type === "table") {
        const d = document.createElement("div"); d.className = "artifact";
        d.innerHTML = `<div class="a-title">${esc(a.title)}</div>${table(a.columns, a.rows)}`; host.appendChild(d);
      } else if (a.type === "drafts") {
        const d = document.createElement("div"); d.className = "artifact";
        d.innerHTML = `<div class="a-title">${esc(a.title)} <a class="btn" href="/queue">Review in Approval queue &rarr;</a></div>` +
          a.drafts.map((x) => `<div class="draft"><b>#${x.id}</b> ${esc(x.account || "")} &middot; <span class="mut">${esc(x.to_email)}</span><br>${esc(x.subject)}` +
            (x.rationale ? `<div class="mut small">why: ${esc(x.rationale)}</div>` : "") + "</div>").join("");
        host.appendChild(d);
      } else if (a.type === "escalation") {
        const d = document.createElement("div"); d.className = "artifact esc-" + esc(a.severity);
        d.innerHTML = `<div class="a-title">&#9873; Escalated to a human: ${esc(a.title)} <a class="btn" href="/escalations">Open Escalations &rarr;</a></div>`;
        host.appendChild(d);
      }
    }
  }

  // ---------- conversation
  function bubble(role, html, runId) {
    const m = document.createElement("div");
    m.className = "msg " + role;
    m.innerHTML = `<div class="who">${role === "user" ? "You" : (mode === "openclaw" ? "OpenClaw agent" : "Revenue agent")}` +
      (runId ? ` <a href="#" class="tracelink" data-run="${runId}">trace</a>` : "") + `</div><div class="body">${html}</div>`;
    $("#msgs").appendChild(m);
    $("#msgs").scrollTop = $("#msgs").scrollHeight;
    return m;
  }
  async function loadHistory() {
    $("#msgs").innerHTML = "";
    const r = await fetch(`/api/chat/${session}`).then((r) => r.json());
    if (!r.length) bubble("assistant", md(
      "Hi! I'm your **local revenue agent** (NVIDIA Nemotron on this Dell GB10, sandboxed by OpenShell). Ask me about product usage, " +
      "find upsell targets, draft outreach or check replies. I never send email myself: drafts wait for your approval, and anything " +
      "risky is escalated to you."));
    for (const m of r) {
      const b = bubble(m.role, m.role === "user" ? esc(m.content) : md(m.content), m.role === "assistant" ? m.run_id : null);
      if (m.artifacts) renderArtifacts(JSON.parse(m.artifacts), $(".body", b));
    }
    loadSessions();
  }
  async function loadSessions() {
    const r = await fetch("/api/sessions").then((r) => r.json());
    $("#sessions").innerHTML = r.map((s) => `<a href="#" data-s="${esc(s.session_id)}" class="${s.session_id === session ? "on" : ""}">${esc(s.first.slice(0, 48))}</a>`).join("") ||
      "<span class='mut small'>No conversations yet</span>";
  }

  // ---------- trace panel
  const ICON = { llm: "&#129504;", tool: "&#128295;", guard: "&#128737;", escalation: "&#9873;", info: "&#8505;", error: "&#9888;" };
  function renderTrace(t) {
    const steps = t.steps || [];
    $("#trace-head").innerHTML = `<b>${esc(t.run.agent)}</b> run #${t.run.id} &middot; <span class="st ${t.run.status}">${t.run.status}</span>` +
      (t.run.ms ? ` &middot; ${(t.run.ms / 1000).toFixed(1)}s` : "") + ` &middot; ${steps.length} steps` +
      ` <a href="/traces/${t.run.id}" target="_blank">open</a>`;
    $("#trace").innerHTML = steps.map((s) => `<details class="step ${s.kind} ${s.status}"><summary><span class="ic">${ICON[s.kind] || "&bull;"}</span>` +
      `<span class="agent">${esc(s.agent)}</span> <b>${esc(s.name)}</b><span class="ms">${s.ms != null ? s.ms + "ms" : ""}</span></summary>` +
      (s.input ? `<div class="lbl">input</div><pre>${esc(pretty(s.input))}</pre>` : "") +
      (s.output ? `<div class="lbl">output</div><pre>${esc(pretty(s.output))}</pre>` : "") + "</details>").join("") +
      (t.run.status === "running" ? `<div class="thinking">agent working<span class="dots"></span></div>` : "");
    $("#trace").scrollTop = $("#trace").scrollHeight;
  }
  function pretty(s) { try { return JSON.stringify(JSON.parse(s), null, 2); } catch (e) { return s; } }
  async function showRun(id) { renderTrace(await fetch(`/api/runs/${id}`).then((r) => r.json())); }

  async function send(text) {
    if (busy || !text.trim()) return;
    busy = true; $("#send").disabled = true;
    bubble("user", esc(text));
    const pending = bubble("assistant", `<div class="thinking">thinking<span class="dots"></span></div>`);
    const { run_id } = await fetch("/api/chat", { method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ session_id: session, message: text, mode }) }).then((r) => r.json());
    $(".who", pending).innerHTML += ` <a href="#" class="tracelink" data-run="${run_id}">trace</a>`;
    for (;;) {
      await new Promise((r) => setTimeout(r, 900));
      const t = await fetch(`/api/runs/${run_id}`).then((r) => r.json());
      renderTrace(t);
      const live = (t.steps || []).slice(-1)[0];
      if (t.run.status === "running") {
        $(".body", pending).innerHTML = `<div class="thinking">${live ? esc(live.agent + ": " + live.name) : "thinking"}<span class="dots"></span></div>`;
        continue;
      }
      $(".body", pending).innerHTML = md(t.message ? t.message.content : t.run.output || "");
      if (t.message && t.message.artifacts) renderArtifacts(JSON.parse(t.message.artifacts), $(".body", pending));
      break;
    }
    busy = false; $("#send").disabled = false; $("#q").focus();
    $("#msgs").scrollTop = $("#msgs").scrollHeight;
    loadSessions();
  }

  // ---------- wiring
  document.addEventListener("click", (e) => {
    const tl = e.target.closest(".tracelink");
    if (tl) { e.preventDefault(); showRun(tl.dataset.run); document.body.classList.add("show-trace"); }
    const s = e.target.closest("#sessions a");
    if (s) { e.preventDefault(); session = s.dataset.s; store.set("fd-session", session); loadHistory(); }
    const chip = e.target.closest(".chip");
    if (chip) { e.preventDefault(); send(chip.textContent); }
  });
  $("#form").addEventListener("submit", (e) => { e.preventDefault(); const q = $("#q").value; $("#q").value = ""; send(q); });
  $("#new").addEventListener("click", (e) => { e.preventDefault(); session = newId(); store.set("fd-session", session); loadHistory(); });
  $("#mode").value = mode;
  $("#mode").addEventListener("change", (e) => { mode = e.target.value; store.set("fd-mode", mode); });
  $("#toggle-trace").addEventListener("click", (e) => { e.preventDefault(); document.body.classList.toggle("show-trace"); });
  store.set("fd-session", session);
  loadHistory();
})();
